#!/usr/bin/env bash

set -euo pipefail

GATEWAYS=(
    ovpn_gw1_tcp
    ovpn_gw2_tcp
    ovpn_gw3_tcp
    ovpn_gw4_tcp

    ovpn_gw1_udp
    ovpn_gw2_udp
    ovpn_gw3_udp
    ovpn_gw4_udp
)

###############################################################################
# Funktionen
###############################################################################

headline() {
    echo
    echo "========================================"
    echo "$1"
    echo "========================================"
}

###############################################################################
# IPVS stoppen
###############################################################################

headline "Stoppe IPVS"

(
    cd "./ipvs"
    ./down.sh
)

###############################################################################
# Unbound stoppen
###############################################################################

headline "Stoppe Unbound"

(
    cd "./unbound"
    docker compose down
)

###############################################################################
# Gateways stoppen
###############################################################################

headline "Stoppe OpenWrt Gateways"

for gw in "${GATEWAYS[@]}"; do

    echo
    echo "----------------------------------------"
    echo "$gw"
    echo "----------------------------------------"

    (
        cd "./$gw"
        docker compose down
    )

done

###############################################################################
# Fertig
###############################################################################

headline "Alle Container wurden gestoppt"
